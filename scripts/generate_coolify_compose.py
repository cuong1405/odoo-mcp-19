#!/usr/bin/env python3
"""Generate a Coolify Service definition with its Chromium profile provisioned automatically.

Only Python's standard library is needed. Coolify's managed-file ``content``
extension is consumed by Coolify before handing the definition to Docker Compose.
"""

import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GENERATED = ROOT / "docker-compose.coolify.yml"


def render(ref: str = "master") -> str:
    """Embed the vendored profile rather than downloading anything at container startup."""
    if not re.fullmatch(r"[a-zA-Z0-9][a-zA-Z0-9._/-]{0,199}", ref):
        raise ValueError("Git ref must be a branch, tag, or full commit hash")
    profile = json.loads((ROOT / "docker/chromium-seccomp.json").read_text())
    if profile.get("defaultAction") != "SCMP_ACT_ERRNO":
        raise ValueError("Expected the vendored default-deny Chromium seccomp profile")
    embedded = json.dumps(profile, separators=(",", ":"))
    return f"""# Generated by scripts/generate_coolify_compose.py; edit the generator, then regenerate.
# Paste into an EXISTING Coolify Docker Compose Service to preserve its oauth-data volume.
# Coolify-only managed-file content provisions the host profile before container creation.
services:
  mcp:
    build:
      context: 'https://github.com/cuong1405/odoo-mcp-19.git#{ref}'
      args:
        INSTALL_CAPTURE: 'true'
    init: true
    shm_size: '1gb'
    security_opt:
      - seccomp=./chromium-seccomp.json
    volumes:
      - type: bind
        source: ./chromium-seccomp.json
        target: /etc/odoo-mcp/chromium-seccomp.json
        read_only: true
        content: |
          {embedded}
    environment:
      - SERVICE_URL_MCP_8080
      - 'ODOO_URL=${{ODOO_URL:?}}'
      - 'ODOO_DB=${{ODOO_DB:?}}'
      - 'ODOO_USERNAME=${{ODOO_USERNAME:?}}'
      - 'ODOO_API_KEY=${{ODOO_API_KEY:?}}'
      - MCP_TRANSPORT=streamable-http
      - 'MCP_API_KEY=${{MCP_API_KEY:?}}'
      - MCP_HOST=0.0.0.0
      - MCP_PORT=8080
      - 'MCP_SAFETY_MODE=${{MCP_SAFETY_MODE:-strict}}'
      - 'MCP_CAPTURE_ALLOWED_HOSTS=${{MCP_CAPTURE_ALLOWED_HOSTS:-*.leonix.cc}}'
      - 'MCP_CAPTURE_PRIVATE_HOSTS=${{MCP_CAPTURE_PRIVATE_HOSTS:-}}'
      - 'MCP_CAPTURE_CONCURRENCY=${{MCP_CAPTURE_CONCURRENCY:-2}}'
      - 'MCP_CAPTURE_HOURLY_LIMIT=${{MCP_CAPTURE_HOURLY_LIMIT:-60}}'
    restart: unless-stopped

  oauth:
    image: 'ghcr.io/sigbit/mcp-auth-proxy:latest'
    depends_on:
      - mcp
    environment:
      - SERVICE_URL_OAUTH_80
      - 'EXTERNAL_URL=${{OAUTH_PUBLIC_URL:?}}'
      - NO_AUTO_TLS=true
      - 'LISTEN=:80'
      - DATA_PATH=/data
      - 'PROXY_BEARER_TOKEN=${{MCP_API_KEY:?}}'
      - 'PASSWORD=${{PROXY_PASSWORD:?}}'
    command:
      - '--'
      - 'http://mcp:8080/mcp'
    volumes:
      - oauth-data:/data
    restart: unless-stopped

volumes:
  oauth-data: null
"""


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--ref", default="master", help="Fork branch, tag or full commit hash (default: master)")
    parser.add_argument("--output", type=Path, help="Write to this path instead of stdout")
    parser.add_argument("--check", action="store_true", help="Check the generated file matches this script")
    args = parser.parse_args()
    try:
        content = render(args.ref)
    except ValueError as exc:
        parser.error(str(exc))
    if args.check:
        path = args.output or GENERATED
        if not path.exists() or path.read_text() != content:
            parser.exit(1, f"{path.name} is out of date; regenerate with --output\n")
    elif args.output:
        args.output.write_text(content)
    else:
        print(content, end="")


if __name__ == "__main__":
    main()
